'use strict';
// Bundles the variety page reader (tools/reader/) and its HTML parser into one plain script.
// usage: node build_reader.cjs <node_modules-dir holding esbuild and htmlparser2> <out.js>
const fs = require('node:fs'), path = require('node:path'), crypto = require('node:crypto');
const [modules, outFile] = process.argv.slice(2);
const esbuild = require(path.join(modules, 'esbuild'));
const here = path.join(__dirname, 'reader');
const sha = f => crypto.createHash('sha256').update(fs.readFileSync(f)).digest('hex').slice(0, 12);
const parser = JSON.parse(fs.readFileSync(path.join(modules, 'htmlparser2', 'package.json'), 'utf8')).version;
const result = esbuild.buildSync({
  entryPoints: [path.join(here, 'entry.mjs')], bundle: true, write: false, format: 'iife', globalName: '__lrfReader',
  platform: 'browser', target: ['es2020'], minify: true, legalComments: 'none', nodePaths: [modules], charset: 'utf8'
});
const body = result.outputFiles[0].text;
const text = `/* Little River Farm Planner — reads a seed supplier's product page into variety details.
 * Generated by tools/build_reader.cjs; do not edit. Source: tools/reader/entry.mjs (${sha(path.join(here, 'entry.mjs'))}) and
 * tools/reader/variety-link.mjs (${sha(path.join(here, 'variety-link.mjs'))}, the v7.16.169 reader, unchanged), with htmlparser2 ${parser} (MIT).
 */
(function (root) {
${body}
  var api = __lrfReader.default || __lrfReader;
  if (typeof module === 'object' && module.exports) module.exports = api; else root.LRFReader = api;
})(typeof self !== 'undefined' ? self : this);
`;
fs.writeFileSync(outFile, text);
console.log(JSON.stringify({ out: outFile, bytes: text.length, parser }));
